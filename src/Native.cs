        public static void SetBackgroundMode(bool background)
    {
        try
        {
            using var p = System.Diagnostics.Process.GetCurrentProcess();
            p.PriorityClass = background ? System.Diagnostics.ProcessPriorityClass.Idle : System.Diagnostics.ProcessPriorityClass.Normal;
            var st = new PROCESS_POWER_THROTTLING_STATE
            {
                Version = 1,
                ControlMask = PROCESS_POWER_THROTTLING_EXECUTION_SPEED,
                StateMask = background ? PROCESS_POWER_THROTTLING_EXECUTION_SPEED : 0,
            };
            SetProcessInformation(GetCurrentProcess(), ProcessPowerThrottling, ref st, Marshal.SizeOf<PROCESS_POWER_THROTTLING_STATE>());
        }
        catch {  }
    }

